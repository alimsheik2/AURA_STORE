// Process each language
const dictionaries = {};

langs.forEach(lang => {
  const filePath = path.join(localesDir, lang, 'translation.json');
  const dict = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  // Replace old branding in all values
  Object.keys(dict).forEach(k => {
    if (typeof dict[k] === 'string' && dict[k].includes('ShopVerse')) {
      dict[k] = dict[k].replace(/ShopVerse/g, 'AURA-STORE');
    }
  });

  // Apply patches
  if (patches[lang]) {
    Object.entries(patches[lang]).forEach(([k, v]) => {
      dict[k] = v;
    });
  }

  // Apply new keys
  if (newKeys[lang]) {
    Object.entries(newKeys[lang]).forEach(([k, v]) => {
      dict[k] = v;
    });
  }

  // Ensure brand name is consistent
  dict['brand.name'] = 'AURA-STORE';

  dictionaries[lang] = dict;
});

// Ensure all keys from EN exist in every dictionary
const allKeys = Object.keys(dictionaries['en']);
langs.forEach(lang => {
  if (lang === 'en') return;
  allKeys.forEach(k => {
    if (dictionaries[lang][k] === undefined) {
      console.warn(`Key "${k}" missing in ${lang}, falling back to EN`);
      dictionaries[lang][k] = dictionaries['en'][k];
    }
  });

  // Sort keys alphabetically for clean output
  const sorted = {};
  Object.keys(dictionaries[lang]).sort().forEach(k => {
    sorted[k] = dictionaries[lang][k];
  });

  // Write back to public/locales
  fs.writeFileSync(
    path.join(localesDir, lang, 'translation.json'),
    JSON.stringify(sorted, null, 2) + '\n',
    'utf8'
  );
  console.log(`Updated public/locales/${lang}/translation.json (${Object.keys(sorted).length} keys)`);
});

// Write EN sorted as well
const sortedEn = {};
Object.keys(dictionaries['en']).sort().forEach(k => {
  sortedEn[k] = dictionaries['en'][k];
});
fs.writeFileSync(
  path.join(localesDir, 'en', 'translation.json'),
  JSON.stringify(sortedEn, null, 2) + '\n',
  'utf8'
);
console.log(`Updated public/locales/en/translation.json (${Object.keys(sortedEn).length} keys)`);

